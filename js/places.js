/**
 * Ищет в тексте упоминания мест из справочника.
 * Возвращает массив { name, lat, lng } в порядке появления в тексте.
 */
function findPlaces(text, places) {
  const lower = text.toLowerCase();
  const hits = [];
  const seen = new Set();
  places.forEach((p) => {
    let idx = -1;
    p.stems.some((stem) => {
      const at = lower.indexOf(stem);
      if (at !== -1) {
        idx = at;
        return true;
      }
      return false;
    });
    if (idx !== -1 && !seen.has(p.name)) {
      seen.add(p.name);
      hits.push({ name: p.name, lat: p.lat, lng: p.lng, at: idx });
    }
  });
  hits.sort((a, b) => a.at - b.at);
  return hits.map(({ name, lat, lng }) => ({ name, lat, lng }));
}

